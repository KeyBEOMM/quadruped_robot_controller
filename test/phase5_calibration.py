#!/usr/bin/env python3
"""
Phase 5 Servo Calibration Tool
================================
Communicates with ESP32 calibration mode (UDP port 9871)
to control servo angle/PWM in real-time and record calibration results.

Usage:
    python test/phase5_calibration.py              # auto-discover
    python test/phase5_calibration.py 192.168.0.10  # specify IP

Commands:
    set_angle <ch> <deg>    Move servo to specified angle (0~180 clamping)
    set_pwm <ch> <usec>     Direct PWM control (raw, no clamping)
    get_status              Query all channel states
    save_offset <ch> <usec> Record calibration offset (saves to calibration_log.json)
    sweep <ch>              Auto sweep test: 0->90->180->90->0
    help                    Show command list
    quit / exit             Exit
"""

import socket
import sys
import json
import os
import time
import tty
import termios
from datetime import datetime

# =============================================================
# Configuration
# =============================================================
UDP_PORT = 9871
TIMEOUT_SEC = 2.0
LOG_FILE = os.path.join(os.path.dirname(__file__), "calibration_log.json")
HEADER_FILE = os.path.join(os.path.dirname(__file__), "../include/servo_config.h")

# Channel-to-name mapping (channel number -> leg_joint)
CHANNEL_MAP = {
    0: "LF_HAA",  1: "LF_HFE",  2: "LF_KNE",
    3: "RF_HAA",  4: "RF_HFE",  5: "RF_KNE",
    6: "LH_HAA",  7: "LH_HFE",  8: "LH_KNE",
    9: "RH_HAA", 10: "RH_HFE", 11: "RH_KNE",
}


def get_channel_name(ch: int) -> str:
    return CHANNEL_MAP.get(ch, f"CH{ch}")


# =============================================================
# UDP Communication
# =============================================================
class CalibrationClient:
    def __init__(self, esp_ip: str):
        self.esp_ip = esp_ip
        self.sock = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
        self.sock.settimeout(TIMEOUT_SEC)
        print(f"[INFO] Target: {esp_ip}:{UDP_PORT}")

    def send_command(self, cmd: str) -> str:
        """Send command and receive response"""
        try:
            self.sock.sendto(cmd.encode(), (self.esp_ip, UDP_PORT))
            data, _ = self.sock.recvfrom(1024)
            return data.decode('utf-8', errors='replace')
        except socket.timeout:
            return "[TIMEOUT] No response from ESP32. Check WiFi connection / port."

    def close(self):
        self.sock.close()


# =============================================================
# Config & C++ Generator
# =============================================================
def load_log() -> dict:
    default_log = {"board_freq": 25000000, "offsets": {}, "history": []}
    if os.path.exists(LOG_FILE):
        try:
            with open(LOG_FILE, 'r') as f:
                data = json.load(f)
                if "board_freq" not in data:
                    data["board_freq"] = 25000000
                return data
        except Exception:
            pass
    return default_log

def generate_config_header(log: dict):
    # Ensure all 12 channels exist. If not, default to 0.0
    zero_offsets = [[0.0 for _ in range(3)] for _ in range(4)]
    for ch_str, entry in log.get("offsets", {}).items():
        ch = int(ch_str)
        leg = ch // 3
        jnt = ch % 3
        zero_offsets[leg][jnt] = entry.get("delta_deg", 0.0)
    
    board_freq = log.get("board_freq", 25000000)

    header_content = f"""#pragma once
#include <cstdint>

// This file is auto-generated by test/phase5_calibration.py
// DO NOT EDIT MANUALLY unless you know what you are doing.

constexpr uint32_t PCA9685_OSC_FREQ = {board_freq};

constexpr float ZERO_OFFSET[4][3] = {{
    {{{zero_offsets[0][0]:.2f}f, {zero_offsets[0][1]:.2f}f, {zero_offsets[0][2]:.2f}f}}, // LF
    {{{zero_offsets[1][0]:.2f}f, {zero_offsets[1][1]:.2f}f, {zero_offsets[1][2]:.2f}f}}, // RF
    {{{zero_offsets[2][0]:.2f}f, {zero_offsets[2][1]:.2f}f, {zero_offsets[2][2]:.2f}f}}, // LH
    {{{zero_offsets[3][0]:.2f}f, {zero_offsets[3][1]:.2f}f, {zero_offsets[3][2]:.2f}f}}  // RH
}};
"""
    with open(HEADER_FILE, 'w') as f:
        f.write(header_content)
    print(f"[CODEGEN] Updated {HEADER_FILE}")

def set_board_freq_log(freq: int):
    log = load_log()
    log["board_freq"] = freq
    with open(LOG_FILE, 'w') as f:
        json.dump(log, f, indent=2, ensure_ascii=False)
    generate_config_header(log)

def save_offset_to_log(ch: int, measured_us: float, response: str):
    log = load_log()
    ch_name = get_channel_name(ch)
    nominal_us = 1500.0  # 90 deg nominal
    delta_us = measured_us - nominal_us
    delta_deg = (delta_us / 2000.0) * 180.0

    entry = {
        "channel": ch,
        "name": ch_name,
        "measured_us": measured_us,
        "nominal_us": nominal_us,
        "delta_us": round(delta_us, 1),
        "delta_deg": round(delta_deg, 2),
        "timestamp": datetime.now().isoformat(),
    }

    log["offsets"][str(ch)] = entry
    log["history"].append(entry)

    with open(LOG_FILE, 'w') as f:
        json.dump(log, f, indent=2, ensure_ascii=False)

    print(f"[LOG] {ch_name} offset saved: delta={delta_us:+.0f}us ({delta_deg:+.1f} deg)")
    generate_config_header(log)


