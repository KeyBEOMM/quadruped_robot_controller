# =============================================================
# Main REPL
# =============================================================
def main():
    # Determine IP address
    if len(sys.argv) > 1:
        esp_ip = sys.argv[1]
    else:
        esp_ip = input("Enter ESP32 IP address (e.g. 192.168.0.10): ").strip()
        if not esp_ip:
            print("[ERROR] IP address is required.")
            sys.exit(1)

    client = CalibrationClient(esp_ip)

    # Connection test
    print("[INFO] Testing ESP32 connection...")
    resp = client.send_command("get_status")
    if "TIMEOUT" in resp:
        print(f"[WARN] {resp}")
        print("[WARN] Make sure ESP32 is in calibration mode.")
        print("[WARN]   Build: pio run -e esp32dev_calibration -t upload")
        proceed = input("Continue anyway? (y/n): ").strip().lower()
        if proceed != 'y':
            client.close()
            sys.exit(0)
    else:
        print("[OK] ESP32 responded.")
        print(resp)

    print(HELP_TEXT)

    # REPL loop
    while True:
        try:
            cmd = input("\n> ").strip()
        except (KeyboardInterrupt, EOFError):
            print("\n[EXIT] Shutting down.")
            break

        if not cmd:
            continue

        # Local command handling
        if cmd.lower() in ("quit", "exit", "q"):
            print("[EXIT] Shutting down.")
            break
        elif cmd.lower() == "help":
            print(HELP_TEXT)
            continue
        elif cmd.lower().startswith("sweep_pwm"):
            parts = cmd.split()
            if len(parts) == 4:
                try:
                    ch = int(parts[1])
                    min_us = float(parts[2])
                    max_us = float(parts[3])
                    run_sweep_pwm(client, ch, min_us, max_us)
                except ValueError:
                    print("[ERROR] sweep_pwm <channel> <min_us> <max_us>")
            else:
                print("[ERROR] Usage: sweep_pwm <ch> <min_us> <max_us>")
            continue
        elif cmd.lower().startswith("jog"):
            parts = cmd.split()
            if len(parts) >= 2:
                try:
                    ch = int(parts[1])
                    start_us = float(parts[2]) if len(parts) >= 3 else 1500.0
                    run_jog(client, ch, start_us)
                except ValueError:
                    print("[ERROR] jog <channel> [start_us]")
            else:
                print("[ERROR] Usage: jog <ch> [start_us]")
            continue
        elif cmd.lower().startswith("sweep"):
            parts = cmd.split()
            if len(parts) == 2:
                try:
                    ch = int(parts[1])
                    run_sweep(client, ch)
                except ValueError:
                    print("[ERROR] sweep <channel_number>")
            else:
                print("[ERROR] Usage: sweep <channel>")
            continue

        # save_offset also saves locally
        if cmd.startswith("save_offset"):
            parts = cmd.split()
            if len(parts) == 3:
                try:
                    ch = int(parts[1])
                    usec = float(parts[2])
                    resp = client.send_command(cmd)
                    print(f"[ESP32] {resp}")
                    save_offset_to_log(ch, usec, resp)
                except ValueError:
                    print("[ERROR] save_offset <channel> <usec>")
            else:
                print("[ERROR] Usage: save_offset <channel> <usec>")
            continue
            
        if cmd.startswith("set_board_freq"):
            parts = cmd.split()
            if len(parts) == 2:
                try:
                    freq = int(parts[1])
                    resp = client.send_command(cmd)
                    print(f"[ESP32] {resp}")
                    set_board_freq_log(freq)
                except ValueError:
                    print("[ERROR] Frequency must be an integer (e.g., 25000000)")
            else:
                print("[ERROR] Usage: set_board_freq <freq>")
            continue

        # Send to ESP32
        resp = client.send_command(cmd)
        print(f"[ESP32] {resp}")

    client.close()


if __name__ == "__main__":
    main()
