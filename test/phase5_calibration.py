# Jog Control
# =============================================================
def _read_key() -> str:
    """Read a single keypress (raw mode). Returns a string token."""
    fd = sys.stdin.fileno()
    old_settings = termios.tcgetattr(fd)
    try:
        tty.setraw(fd)
        ch = sys.stdin.read(1)
        if ch == '\x1b':
            # Escape sequence — read up to 2 more bytes
            next1 = sys.stdin.read(1)
            if next1 == '[':
                next2 = sys.stdin.read(1)
                return f'\x1b[{next2}'   # e.g. '\x1b[A'
            return '\x1b'
        return ch
    finally:
        termios.tcsetattr(fd, termios.TCSADRAIN, old_settings)


def _us_to_deg(us: float) -> float:
    """Convert PWM microseconds to approximate angle (500us=0°, 2500us=180°)."""
    return (us - 500.0) / 2000.0 * 180.0


def run_jog(client: CalibrationClient, ch: int, start_us: float = 1500.0):
    """
    Interactive jog mode.

    Keys:
        ↑  / ↓   : ±10 us
        →  / ←   : ±1 us  (fine)
        S        : save_offset at current position
        Q / Esc  : exit jog mode
    """
    current_us = float(start_us)
    PWM_MIN, PWM_MAX = 500.0, 2500.0
    ch_name = get_channel_name(ch)

    print(f"\n[JOG] Channel {ch} ({ch_name})  start={int(current_us)}us")
    print("[JOG] ↑/↓ = ±10us   →/← = ±1us   S = save_offset   Q/Esc = quit\n")

    # Move to start position immediately
    client.send_command(f"set_pwm {ch} {current_us}")

    def _status_line():
        deg = _us_to_deg(current_us)
        return (f"\r[JOG] ch={ch} ({ch_name})  "
                f"PWM={int(current_us):4d}us  angle≈{deg:6.1f}°   "
                f"(↑↓±10  ←→±1  S=save  Q=quit)  ")

    sys.stdout.write(_status_line())
    sys.stdout.flush()

    while True:
        key = _read_key()

        if key == '\x1b[A':      # ↑
            delta = +10.0
        elif key == '\x1b[B':    # ↓
            delta = -10.0
        elif key == '\x1b[C':    # →
            delta = +1.0
        elif key == '\x1b[D':    # ←
            delta = -1.0
        elif key.lower() == 's':
            # Save offset at current position
            print()
            save_offset_to_log(ch, current_us, "")
            sys.stdout.write(_status_line())
            sys.stdout.flush()
            continue
        elif key.lower() in ('q', '\x1b', '\x03'):   # Q / Esc / Ctrl-C
            print(f"\n[JOG] Exited. Final PWM={int(current_us)}us "
                  f"(≈{_us_to_deg(current_us):.1f}°)")
            break
        else:
            continue

        new_us = current_us + delta
        if new_us < PWM_MIN:
            new_us = PWM_MIN
        elif new_us > PWM_MAX:
            new_us = PWM_MAX

        if new_us != current_us:
            current_us = new_us
            client.send_command(f"set_pwm {ch} {current_us}")
            sys.stdout.write(_status_line())
            sys.stdout.flush()


# =============================================================
# Sweep Test
# =============================================================
def run_sweep(client: CalibrationClient, ch: int):
    """Sequential move through 0->90->180->90->0 with pauses"""
    angles = [0, 45, 90, 135, 180, 135, 90, 45, 0]
    print(f"\n[SWEEP] Channel {ch} ({get_channel_name(ch)})")
    print(f"[SWEEP] Sequence: {' -> '.join(map(str, angles))}")
    print(f"[SWEEP] 1.5s pause at each position")
    print()

    for angle in angles:
        resp = client.send_command(f"set_angle {ch} {angle}")
        print(f"  -> {angle:3d} deg : {resp.strip()}")
        time.sleep(1.5)

    print(f"\n[SWEEP] Done.")

def run_sweep_pwm(client: CalibrationClient, ch: int, min_us: float, max_us: float):
    """Sequential move from min_us to max_us and back in steps of 5us"""
    print(f"\n[SWEEP_PWM] Channel {ch} ({get_channel_name(ch)})")
    print(f"[SWEEP_PWM] Sweeping from {int(min_us)} to {int(max_us)} in steps of 5us")
    print(f"[SWEEP_PWM] Press Ctrl+C to stop early (if needed)\n")

    pwms = []
    curr = min_us
    while curr <= max_us:
        pwms.append(curr)
        curr += 5.0
    
    # Add reverse path
    pwms.extend(pwms[-2::-1])

    try:
        for pwm_val in pwms:
            resp = client.send_command(f"set_pwm {ch} {pwm_val}")
            sys.stdout.write(f"\r  -> {int(pwm_val):4d} us : {resp.strip()}")
            sys.stdout.flush()
            time.sleep(1)  # 50ms for smooth motion
    except KeyboardInterrupt:
        print("\n[SWEEP_PWM] Interrupted by user.")

    print(f"\n[SWEEP_PWM] Done.")


